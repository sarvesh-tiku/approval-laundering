    mac.add("verifierDisagreements", sum(t["verifier_guard_disagreements"] for t in det))
    mac.add("nLegit", sum(1 for t in inv_ep if t["category"] in (1, 4)))

    summary = {}
    for arm, ts in by.items():
        r = {"givr": M.givr(ts, **kw), "uar": M.uar(ts, **kw), "frr": M.frr(ts, **kw), "ltcr": M.ltcr(ts, **kw), "gap": M.approval_execution_gap(ts), "severity": M.severity(ts),
             "scope_breach": sum(t["scope_over_cents"] > 0 for t in ts if t["family"] in SCOPE_FAMILIES)}
        summary[arm] = r
        if arm in TEX:
            k = TEX[arm]
            mac.rate("givr" + k, r["givr"]); mac.rate("uar" + k, r["uar"]); mac.rate("frr" + k, r["frr"]); mac.rate("ltcr" + k, r["ltcr"])
            mac.add("sev" + k, f"\\${r['severity']['mean_cents'] / 100:,.0f}")
            mac.add("scope" + k, r["scope_breach"])
            mac.add("unsafeN" + k, r["gap"]["unsafe_approvals"]); mac.add("commitN" + k, r["gap"]["committed_violations"])
            mac.add("gap" + k, f"{100 * r['gap']['gap']:.1f}\\%")
            mac.add("givrK" + k, int(r["givr"]["k"]))
    A["by_arm"] = summary
    with open(RES / "summary_by_arm.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["arm", "givr", "givr_lo", "givr_hi", "uar", "uar_lo", "uar_hi", "frr", "frr_lo", "frr_hi", "ltcr", "ltcr_lo", "ltcr_hi", "episodes", "mean_severity_usd", "scope_breaches"])
        for arm, r in summary.items():
            w.writerow([arm] + [r[m][x] for m in ("givr", "uar", "frr", "ltcr") for x in ("rate", "lo", "hi")] + [int(r["givr"]["n"]), r["severity"]["mean_cents"] / 100, r["scope_breach"]])

