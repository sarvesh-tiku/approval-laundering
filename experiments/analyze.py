    with open(RES / "table_main.tex", "w") as f:
        for arm in MAIN:
            r = summary[arm]
            g = r["givr"]
            gs = f"{100 * g['rate']:.1f} {fmt_ci(g)}" if g["k"] else f"0 (0/{int(g['n'])}; $\\leq${100 * g['upper95']:.1f})"
