def _dot_panel(ax, rows, xlabel, zero_note=True):
    """rows: list of (label, ci-dict). Point + interval; zero-event arms show an open marker with an upper bound."""
    ys = list(range(len(rows)))[::-1]
    for y, (lab, r) in zip(ys, rows):
        if r["k"] == 0:
            hi = r.get("upper95", 0)
            ax.plot([0, 100 * hi], [y, y], color=BLUE, lw=1.6, solid_capstyle="round")
            ax.plot(0, y, "o", ms=6, mfc="white", mec=BLUE, mew=1.5, zorder=3, clip_on=False)
            ax.annotate(f"0 of {int(r['n'])} (95% upper {100 * hi:.1f}%)", (100 * hi + 2, y), va="center", fontsize=7.5, color=MUTED)
        else:
            ax.plot([100 * r["lo"], 100 * r["hi"]], [y, y], color=BLUE, lw=1.6, solid_capstyle="round")
            ax.plot(100 * r["rate"], y, "o", ms=6, color=BLUE, zorder=3, clip_on=False)
            ax.annotate(f"{100 * r['rate']:.1f}%", (100 * r["hi"] + 2, y), va="center", fontsize=7.5, color=MUTED)
    ax.set_yticks(ys); ax.set_yticklabels([x[0] for x in rows])
    ax.set_xlim(0, 112); ax.set_xticks([0, 25, 50, 75, 100]); ax.set_xlabel(xlabel); ax.grid(axis="y", visible=False); ax.tick_params(length=0)


