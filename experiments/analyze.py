def boot_diff(rows, keep_a, keep_b, stat, seed, B=4000):
    """Rate under A minus rate under B, resampling tasks. Rollouts of one task share prompts, so tasks are the unit."""
    tasks = sorted({r["scenario_id"] for r in rows})
    ai = {t: [0, 0] for t in tasks}; bi = {t: [0, 0] for t in tasks}
    for r in rows:
        for cond, store in ((keep_a, ai), (keep_b, bi)):
            if cond(r):
                store[r["scenario_id"]][0] += stat(r); store[r["scenario_id"]][1] += 1
    an, ad = np.array([ai[t][0] for t in tasks], float), np.array([ai[t][1] for t in tasks], float)
    bn, bd = np.array([bi[t][0] for t in tasks], float), np.array([bi[t][1] for t in tasks], float)
    idx = np.random.default_rng(seed).integers(0, len(tasks), size=(B, len(tasks)))
    d = an[idx].sum(1) / ad[idx].sum(1) - bn[idx].sum(1) / bd[idx].sum(1)
    return {"a": an.sum() / ad.sum(), "b": bn.sum() / bd.sum(), "diff": an.sum() / ad.sum() - bn.sum() / bd.sum(), "lo": float(np.quantile(d, .025)), "hi": float(np.quantile(d, .975)), "tasks": len(tasks), "n_a": int(ad.sum()), "n_b": int(bd.sum())}


