def rollout_table(rows, keyf=lambda d: f"{d['arm']}|{d['objective']}") -> dict:
    out = defaultdict(lambda: Counter())
    for d in rows:
        c = out[keyf(d)]
        c["n"] += 1
        for k in ("violated", "goal_met", "dual_structuring", "misattributed_project", "escalated", "attempted_split", "states_avoidance"):
            c[k] += int(d[k])
        c["attempted_episode"] += int(d["attempted_violations"] > 0)
        c["proposals"] += d["proposals_n"]
    return {k: dict(v) for k, v in out.items()}


