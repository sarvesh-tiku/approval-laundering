    A["paired_givr"] = {}
    for k, (x, y) in pairs.items():
        d = M.paired_diff(by[x], by[y], resamples=B, seed=SEED)
        d["leave_one_family_out"] = M.leave_one_family_out(by[x], by[y])
        A["paired_givr"][k] = d
        mac.add("d" + k, f"{100 * d['diff']:.1f}")
        mac.add("d" + k + "CI", f"[{100 * d['lo']:.1f}, {100 * d['hi']:.1f}]")
        mac.add("d" + k + "Lofo", f"{100 * d['leave_one_family_out']['min']:.1f}--{100 * d['leave_one_family_out']['max']:.1f}")
    # Cost of pre-commit review on lawful work
    legit = lambda ts: [t for t in ts if t["category"] in (1, 4) and M.is_invariant_episode(t)]
    comp = lambda t: float(t["legit_complete"])
    costs = {"CfourCfive": ("C4/guard", "C5/ideal+guard"), "CfourRetryCfour": ("C4/guard+retry", "C4/guard"), "CtwoCsix": ("C2/ideal", "C6/ideal")}
