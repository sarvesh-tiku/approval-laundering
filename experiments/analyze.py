    mac.add("nScenarios", len(by["C0/ideal"]))
    mac.add("nInvariantScenarios", len(inv_ep))
    mac.add("nScopeScenarios", len(by["C0/ideal"]) - len(inv_ep))
    mac.add("nTwinClusters", len({t["twin_id"] for t in by["C0/ideal"]}))
    mac.add("nFamilies", len({t["family"] for t in by["C0/ideal"]}))
    mac.add("nSeedsFamily", len({t["seed"] for t in by["C0/ideal"]}))
    mac.add("nArms", len(by))
    mac.add("nEpisodes", f"{len(det):,}")
    mac.add("nProposals", f"{sum(len(M.steps_first_attempt(t)) for t in by['C0/ideal'] if M.is_invariant_episode(t)):,}")
