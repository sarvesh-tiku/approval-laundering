    A["c6_lost_lawful_vs_c2"] = dict(Counter(t["family"] for t, u in zip(sorted(legit(by["C6/ideal"]), key=lambda t: t["scenario_id"]), sorted(legit(by["C2/ideal"]), key=lambda t: t["scenario_id"])) if u["legit_complete"] and not t["legit_complete"]))
